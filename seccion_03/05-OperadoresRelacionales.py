# Operador igualdad (==)
r = 50 == 100
print ("El resultado de la comparación es: ", r)

r = 100 == 100
print ("El resultado de la comparación es: ", r)

# Operador desigualdad (!=)
r = 100 != 100
print ("El resultado de la comparación es: ", r)

# Operador menor que (<)
r = 50 < 100
print ("El resultado de la comparación es: ", r)

# Operador menor o igual que (<=)
r = 100 <= 100
print ("El resultado de la comparación es: ", r)

# Operador mayor que (>)
r = 100 > 50
print ("El resultado de la comparación es: ", r)

# Operador mayor o igual que (>=)
r = 100 >= 100
print ("El resultado de la comparación es: ", r)
array = ["futbol", "pc", 18.6, 45, [6, 7, 8], True, False]
print(array)

print(array[1]) # Segundo elemento
print(array[4]) # Quinto elemento
print(array[-1]) # Último elemento
print(array[-3]) # Tercer elemento contando desde el final
print(array[:2]) # Primeros dos elementos
print(array[1:3]) # Segundo y tercer elementos
print(array[2:]) # Desde el tercer elemento hasta el final